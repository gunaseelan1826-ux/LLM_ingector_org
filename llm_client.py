"""
llm_client.py
Handles forwarding safe prompts to the Gemini Large Language Model.
"""

import os
import json
import urllib.request
import urllib.error
from dotenv import load_dotenv

# Load .env file
load_dotenv()


def get_api_key():
    return os.getenv("GEMINI_API_KEY", "").strip()


def query_llm(prompt_text: str):
    """
    Forwards a verified safe prompt to Gemini.
    Returns a tuple: (response_text, error_message)
    """
    api_key = get_api_key()
    if not api_key:
        return None, "API Key is not set in .env. Prompt was verified Safe by detector."

        # Gemini API generateContent endpoint
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent?key={api_key}"
    payload = {
        "contents": [
            {
                "parts": [{"text": prompt_text}]
            }
        ]
    }

    try:
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data,
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=12) as response:
            result = json.loads(response.read().decode("utf-8"))
            candidates = result.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return parts[0].get("text", "").strip(), None
            return "No response generated by model.", None

    except urllib.error.HTTPError as e:
        raw_error = e.read().decode("utf-8")
        try:
            err_data = json.loads(raw_error)
            msg = err_data.get("error", {}).get("message", str(e))
        except Exception:
            msg = str(e)
        return None, f"Gemini API Error: {msg}"
    except Exception as e:
        return None, f"Connection Error: {str(e)}"
